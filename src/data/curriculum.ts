export const TOTAL_LEVELS = LEVELS.length;
export const TOTAL_QUESTIONS = LEVELS.reduce((sum, l) => sum + l.questions.length, 0);
export const TOTAL_XP = LEVELS.reduce((sum, l) => sum + l.xpReward, 0);

export function getLevel(id: number): Level | undefined {
  return LEVELS.find((l) => l.id === id);
}

export function getChapter(id: number): Chapter | undefined {
  return CHAPTERS.find((c) => c.id === id);
}

export function getLevelQuestions(levelId: number): Question[] {
  return getLevel(levelId)?.questions ?? [];
}

/** XP earned per correct answer based on difficulty */
export function xpForDifficulty(d: Difficulty): number {
  if (d === "سهل") return 10;
  if (d === "متوسط") return 15;
  return 20;
}

/** Normalize Arabic text answers for comparison */
export function normalizeAnswer(s: string): string {
  return s
    .trim()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ")
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)));
}

export function checkTextAnswer(user: string, q: Question): boolean {
  const norm = normalizeAnswer(user);
  const candidates = [q.correctAnswer, ...(q.acceptableAnswers ?? [])].map(normalizeAnswer);
  return candidates.includes(norm);
}
